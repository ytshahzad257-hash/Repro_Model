"""One-command reproduction driver."""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "experiments"))
sys.path.insert(0, str(ROOT / "scripts"))

from common import GENERATED, ensure_outputs, provenance
from reproduce_table4 import run as run_table4
from reproduce_table5 import run as run_table5
from reproduce_table6 import run as run_table6
from reproduce_table7 import run as run_table7
from question_bounds import run as run_bounds
from reproduce_fig5 import plot as plot_fig5
from reproduce_fig8 import plot as plot_fig8
from reproduce_fig9 import plot as plot_fig9
from cross_checkers import run as run_cross_check


def run_command(command: list[str]) -> tuple[int, str]:
    completed = subprocess.run(command, cwd=ROOT, text=True, capture_output=True)
    return completed.returncode, completed.stdout + completed.stderr


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--fast", action="store_true", help="run unit-scale synthetic data and omit K=4 plotting")
    args = parser.parse_args()
    ensure_outputs()
    statuses: list[tuple[str, str, str]] = []
    # Dependency-free checks always run. Pytest is optional in the current
    # source workspace but is required by the declared clean environment.
    code, output = run_command([sys.executable, "-m", "pytest", "-q"])
    statuses.append(("Python tests", "PASS" if code == 0 else "WARNING", output[-4000:]))
    run_table4()
    statuses.append(("Table 4", "PASS", "generated"))
    if args.fast:
        run_table6()
        run_table7(workflows_per_setting=100)
        run_bounds()
        plot_fig5()
        plot_fig9()
    else:
        run_table5()
        run_table6()
        run_table7(workflows_per_setting=2000)
        run_bounds()
        plot_fig5()
        plot_fig8()
        plot_fig9()
    statuses.append(("Tables 5-7", "PASS", "generated"))
    statuses.append(("Figures 5, 8, 9", "PASS" if not args.fast else "WARNING", "generated" if not args.fast else "Figure 8 omitted in fast mode"))
    tlc_code, tlc_output = run_command([sys.executable, "scripts/run_tlc.py"])
    statuses.append(("TLC", "PASS" if tlc_code == 0 and "unavailable" not in tlc_output else "WARNING", tlc_output[-2000:]))
    cross = run_cross_check()
    statuses.append(("Cross-checker", cross["status"], cross.get("reason", "")))
    compare_code, compare_output = run_command([sys.executable, "scripts/compare_with_manuscript.py"])
    comparison_path = GENERATED / "manuscript_comparison.json"
    comparison = json.loads(comparison_path.read_text(encoding="utf-8")) if comparison_path.exists() else {}
    mismatch_count = int(comparison.get("mismatch_count", 0))
    comparison_status = "PASS" if compare_code == 0 and mismatch_count == 0 else "WARNING"
    statuses.append(("Manuscript comparison", comparison_status, f"generated comparison report; unexplained mismatches={mismatch_count}"))
    manifest_code, manifest_output = run_command([sys.executable, "scripts/build_manifest.py"])
    statuses.append(("Artifact manifest", "PASS" if manifest_code == 0 else "WARNING", manifest_output[-1000:]))
    lines = [
        "# Reproduction report",
        "",
        "Generated by `python experiments/run_all.py`.",
        "",
        "| Check | Status | Evidence |",
        "| --- | --- | --- |",
    ]
    lines.extend(f"| {name} | {status} | {detail.replace(chr(10), ' ')[:500]} |" for name, status, detail in statuses)
    lines.extend([
        "",
        "Paper values are treated as external assertions. A mismatch is retained in `docs/MANUSCRIPT_CONSISTENCY_REPORT.md`.",
        "",
        "The current source environment uses Python 3.13 and OpenJDK 17; the manuscript states Python 3.12.3, OpenJDK 21.0.10, and TLC 2026.09.25. These differences are environment findings, not scientific result adjustments.",
    ])
    (GENERATED / "REPRODUCTION_REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (GENERATED / "REPRODUCTION_REPORT.metadata.json").write_text(json.dumps(provenance(experiment="run_all", inputs={"fast": args.fast}), indent=2) + "\n", encoding="utf-8")
    return 1 if cross["status"] == "FAIL" or manifest_code != 0 else 0


if __name__ == "__main__":
    raise SystemExit(main())
