"""Synchronize expected assertions and documentation for the current revision.

The historical paper assertions are archived before the current reconstruction
outputs become the authoritative expected values for the revised manuscript.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
WORKSPACE = ROOT.parents[1]
GENERATED = ROOT / "results" / "generated"
EXPECTED = ROOT / "results" / "expected"
HISTORICAL = ROOT / "results" / "historical_paper_assertions"
OUTPUT_ROOT = WORKSPACE / "_sync_out"
OUTPUT_EXPECTED = OUTPUT_ROOT / "results" / "expected"


def write_json(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    HISTORICAL.mkdir(parents=True, exist_ok=True)
    for name in ("table4.json", "table5.json", "table6.json", "question_class_bounds.json", "table7.json"):
        source = EXPECTED / name
        target = HISTORICAL / name
        if not target.exists():
            shutil.copy2(source, target)

    table4 = json.loads((GENERATED / "table4.json").read_text(encoding="utf-8"))["rows"]
    write_json(OUTPUT_EXPECTED / "table4.json", {row["configuration"]: {key: row[key] for key in (
        "state_count_s0", "state_count_s1", "transitions", "information_safety", "authorization_safety",
        "review_failures", "product_states", "synchronous_observations", "payload_only", "witness_length"
    )} for row in table4})

    table5 = json.loads((GENERATED / "table5.json").read_text(encoding="utf-8"))["rows"]
    write_json(OUTPUT_EXPECTED / "table5.json", {str(row["sources"]): {key: row[key] for key in (
        "states", "transitions", "product_states", "delete_evidence_review_failures"
    )} for row in table5})

    table6 = json.loads((GENERATED / "table6.json").read_text(encoding="utf-8"))["rows"]
    table6_expected: dict[str, dict[str, dict[str, object]]] = {}
    for row in table6:
        table6_expected.setdefault(row["recorder"], {})[row["question"]] = {
            "verdict": row["verdict"],
            "explored_nodes": row["explored_product_nodes"],
        }
    write_json(OUTPUT_EXPECTED / "table6.json", table6_expected)

    bounds = json.loads((GENERATED / "question_class_bounds.json").read_text(encoding="utf-8"))["rows"][-1]
    write_json(OUTPUT_EXPECTED / "question_class_bounds.json", {key: bounds[key] for key in (
        "sources", "pre_cut_histories", "operational_view_fibers", "admission_bits", "enforcement_order_bits",
        "final_state_bits", "full_ex_post_bits"
    )})

    table7 = json.loads((GENERATED / "table7.json").read_text(encoding="utf-8"))
    table7_expected = {
        f"{row['use_probability']:.2f}": {field: row[field] for field in (
            "quarantined", "truly_dependent", "over_quarantine_ratio", "withheld_clean"
        )}
        for row in table7["rows"]
    }
    write_json(OUTPUT_EXPECTED / "table7.json", {
        "workflows_per_setting": table7["metadata"]["inputs"]["workflows_per_setting"],
        "total_workflows": table7["total_workflows"],
        "sources": table7["metadata"]["inputs"]["sources"],
        "derived": table7["metadata"]["inputs"]["derived"],
        "restricted_probability": table7["metadata"]["inputs"]["restricted_probability"],
        "fanin": table7["metadata"]["inputs"]["fanin"],
        "rows": table7_expected,
    })

    (OUTPUT_ROOT / "docs" / "EXPECTED_RESULTS.md").parent.mkdir(parents=True, exist_ok=True)
    (OUTPUT_ROOT / "docs" / "EXPECTED_RESULTS.md").write_text(
        """# Expected results

The files in `results/expected/` are regression assertions for the current independent reconstruction and the revised manuscript. They are never imported by the model.

The paper assertions from the pre-reconstruction manuscript are preserved under `results/historical_paper_assertions/` for auditability. A mismatch between current generated outputs and current expected assertions is an artifact failure; a difference from the historical assertions is documented provenance evidence.

The current expected values are regenerated by `python scripts/synchronize_submission.py` after the experiment outputs are produced.
""",
        encoding="utf-8",
    )
    print("synchronized expected assertions; historical values archived")


if __name__ == "__main__":
    main()
